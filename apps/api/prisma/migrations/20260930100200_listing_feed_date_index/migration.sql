-- Лента по дате при широком радиусе и «Весь Дагестан» (ADR-0010).
--
-- Когда в круг попадает большая часть объявлений (25–100 км вокруг
-- Махачкалы), база без этого индекса читает все подходящие строки и
-- сортирует их ради первых двадцати. С ним — идёт по ленте от свежих и
-- останавливается, набрав страницу. Существующие индексы ленты начинаются
-- с city_id и при поиске по кругу, без города, не помогают.
CREATE INDEX "listings_feed_bumped_idx"
  ON "listings" ("bumped_at" DESC, "id")
  WHERE "deleted_at" IS NULL AND "status" = 'approved';
