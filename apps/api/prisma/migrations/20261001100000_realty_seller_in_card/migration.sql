-- «Кто разместил» у недвижимости показывается в строке карточки:
-- «от собственника · 2 комн. · 54 м²» (ТЗ «Объявления», п. 13).
--
-- Флаги полей правятся из панели, и повторный seed их не перезаписывает,
-- поэтому включение показа в карточке — отдельной миграцией. Идемпотентна:
-- трогает одно поле и ставит одно значение.
UPDATE "listing_attribute_definitions"
SET "show_in_card" = true
WHERE "key" = 'sellerType';
