/**
 * Данные пользователя, прикреплённые к запросу после проверки токена.
 *
 * Права (permissions) кладутся прямо в токен, чтобы не ходить в базу при
 * каждом запросе. Плата за это — задержка вступления изменений в силу:
 * если у сотрудника отобрали право, оно перестанет действовать после
 * истечения access-токена (15 минут). Для мгновенной блокировки
 * предусмотрен отзыв всех сессий пользователя.
 */
export interface RequestUser {
  /** Идентификатор пользователя */
  id: string;
  phone: string;
  roles: string[];
  permissions: string[];
  /** Идентификатор конкретного токена — нужен для отзыва отдельной сессии */
  tokenId: string;
  /** Партнёрский аккаунт, если пользователь представляет бизнес */
  partnerId?: string;
}

/** Содержимое JWT-токена доступа. */
export interface AccessTokenPayload {
  /** subject — идентификатор пользователя (стандартное поле JWT) */
  sub: string;
  phone: string;
  roles: string[];
  perms: string[];
  /** JWT ID — уникальный номер токена */
  jti: string;
  partnerId?: string;
}
