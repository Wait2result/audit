/**
 * Отсев рекламы.
 *
 * Интернет-реклама в России обязана нести маркировку: пометку «Реклама»,
 * сведения о рекламодателе (ИНН) и токен `erid`. Издания ставят её строкой в
 * конце материала («Реклама | АО "ТАНДЕР" | ИНН … | erid: …»). Это единственный
 * надёжный признак: заметку по смыслу от рекламной без него не отличить.
 *
 * Чего правила не видят: рекламу без маркировки (нарушение закона самим
 * изданием) и «нативные» материалы без пометки. Для таких случаев в панели
 * управления есть ручное скрытие.
 */

/** Токен рекламодателя: `erid: CQH36p…` — длинная строка из латиницы и цифр. */
const ERID = /\berid\b\s*[:=\-–—]?\s*[A-Za-z0-9]{8,}/i;

/** Строка-пометка: «Реклама.», «Реклама | ООО …», «Реклама, 18+ АНО …». */
const AD_LABEL = /(?:^|\n)\s*реклама\s*(?:[.|:,;]|\s+\d{1,2}\+|\s+(?:ООО|АО|ПАО|ИП|АНО|ЗАО)\b)/i;

/** Пометки платных и партнёрских материалов. */
const PAID_LABEL =
  /на правах рекламы|партн[её]рский материал|публикации? от партн[её]ров|платный материал|рекламный материал|пресс-релиз\s*[:|]/i;

export function isAdvertising(title: string, paragraphs: readonly string[] | null): boolean {
  const text = [title, ...(paragraphs ?? [])].join('\n');
  return ERID.test(text) || AD_LABEL.test(text) || PAID_LABEL.test(text);
}

/** Рубрики, в которых издания публикуют платные материалы. */
const PAID_CATEGORY = /реклам|партн[её]р|пресс-релиз|новости компаний/i;

export function isPaidCategory(category: string | null): boolean {
  return category !== null && PAID_CATEGORY.test(category);
}
