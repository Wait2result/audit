/**
 * Текущая палитра с учётом темы (пункт «тёмная тема» этапа 6).
 *
 * Экраны и компоненты вызывают этот хук вместо статического импорта
 * `colors`, когда цвет должен меняться вместе с темой: он возвращает новый
 * объект при каждой смене темы, и `useMemo` на стороне вызывающего кода
 * пересобирает стили. Статический `colors` (светлая палитра) остаётся
 * экспортированным как есть — часть кода намеренно рисует поверх фотографий
 * и брендовых плашек одним и тем же цветом независимо от темы (см.
 * комментарий у `darkColors`), и для них ничего менять не нужно.
 */
export function useThemeColors(): ThemeColors {
  return useIsDarkTheme() ? darkColors : colors;
}

/**
 * Тёмная ли сейчас тема. Нужно там, где тема меняет не цвет, а источник:
 * например, подложку карты (светлые или тёмные тайлы).
 */
export function useIsDarkTheme(): boolean {
  const mode = useThemeStore((s) => s.mode);
  const systemScheme = useColorScheme();

  return mode === 'system' ? systemScheme === 'dark' : mode === 'dark';
}
