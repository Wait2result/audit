import type { WeatherIconName } from '@dagestan/shared';

// ── Фон экрана погоды и виджета — настоящие фотографии, не градиенты ────────

/** Шесть фонов, под которые собраны реальные фотографии (`assets/images/weather`). */
export type WeatherBackgroundKey =
  'clear' | 'partly_cloudy' | 'cloudy' | 'rain' | 'storm' | 'night';

/**
 * Какую из шести фотографий неба показать — и на полном экране погоды, и в
 * виджете на главной (см. `WeatherSkyPhoto.tsx`).
 *
 * Ночь важнее состояния неба: ясно и переменная облачность ночью выглядят
 * одинаково тёмными и сводятся к одному ночному фону — отдельных фото
 * «ясная ночь» и «облачная ночь» нет, а рисовать разницу цветом смысла
 * нет, раз её не видно и наяву. Гроза — исключение: она и днём выглядит
 * почти как ночь (тяжёлые тёмные тучи, вспышка), поэтому остаётся собой
 * в любое время суток, а не сводится к обычной ночи без молнии.
 *
 * У тумана и снега нет отдельной фотографии — по характеру освещения они
 * ближе всего к пасмурному небу (мягкий рассеянный свет без чёткого солнца
 * или дождя), и это честнее, чем выдавать один из шести фонов за то,
 * чем он не является.
 */
export function weatherBackgroundKey(icon: WeatherIconName, isDay: boolean): WeatherBackgroundKey {
  if (icon === 'storm') return 'storm';
  if (!isDay) return 'night';

  switch (icon) {
    case 'sun':
      return 'clear';
    case 'weather':
      return 'partly_cloudy';
    case 'cloud':
    case 'fog':
    case 'snow':
      return 'cloudy';
    case 'rain':
      return 'rain';
  }
}

/** Бирюзовый акцент погоды — фиксированный, не из темы приложения: фон
 *  здесь фотография неба, а не фон приложения, и от выбора светлой или
 *  тёмной темы в профиле не зависит. */
export const WEATHER_ACCENT = '#22CFC2';

/**
 * Стекло карточек поверх фотографии неба — одно и то же на экране погоды и
 * в виджете на главной, чтобы плитки часов выглядели одинаково в обоих местах.
 *
 * Текст на нём всегда белый — фотография неба под стеклом достаточно
 * приглушена размытием и подложкой, чтобы белый читался что днём на ярком
 * небе, что ночью на тёмном. Меняется от дня к ночи только сама подложка:
 * днём светлая (небо и так яркое, тёмная подложка выглядела бы дырой),
 * ночью — тёмная (светлая на почти чёрном небе светилась бы пятном).
 */
export type WeatherSurface = ReturnType<typeof weatherSurface>;

export function weatherSurface(isDay: boolean) {
  const shared = {
    text: '#FFFFFF',
    muted: 'rgba(255,255,255,0.78)',
    faint: 'rgba(255,255,255,0.6)',
    accent: WEATHER_ACCENT,
    track: 'rgba(255,255,255,0.25)',
    /** Подложка выбранного часа — мягкий бирюзовый, не рамка */
    activeTint: 'rgba(34,207,194,0.24)',
  };

  return isDay
    ? {
        ...shared,
        // Карточка деталей — заметнее, но всё ещё стекло, а не сплошной блок
        tint: 'rgba(210,230,240,0.28)',
        // Мелкие плитки (часы, дни) — прозрачнее: их много на экране,
        // и сплошным рядом заметных карточек они спорили бы друг с другом
        tileTint: 'rgba(255,255,255,0.17)',
        border: 'rgba(255,255,255,0.26)',
      }
    : {
        ...shared,
        // Ночное небо тёмное само по себе, поэтому карточка тоже тёмная —
        // светлая на почти чёрном фоне светилась бы отдельным пятном
        tint: 'rgba(20,35,45,0.5)',
        tileTint: 'rgba(15,30,38,0.42)',
        border: 'rgba(150,190,200,0.21)',
      };
}

/**
 * Подложка под фотографией — тёмный тон того же неба, что и на снимке
 * каждого состояния. Видна, пока фотография ещё не отрисована: светлая
 * подложка приложения на это мгновение мелькнула бы белым под белым текстом.
 */
export const WEATHER_BACKGROUND_COLOR: Record<WeatherBackgroundKey, string> = {
  clear: '#1673C7',
  partly_cloudy: '#1F6FB8',
  cloudy: '#395D78',
  rain: '#1C3A4C',
  storm: '#172433',
  night: '#0A1423',
};
