/** Слова без перевода остаются как есть; сочетание целиком «латиницей» не годится. */
export function russianModelAlias(label: string): string | null {
  const parts = label.split(/\s+/);
  let translated = 0;
  const words = parts.map((part) => {
    const word = WORDS[part.toLowerCase()];
    if (word) {
      translated += 1;
      return word;
    }
    return part.toLowerCase();
  });
  if (translated === 0) return null;
  const alias = words.join(' ');
  return alias === label.toLowerCase() ? null : alias;
}
